/* Minimal service worker — required for the phone "install" prompt and gives a
   fast, resilient shell. It uses network-first so data is always fresh (the app
   is live data from Google Sheets), falling back to cache only when offline. */

const CACHE = "ken-tracker-v1";

self.addEventListener("install", (event) => {
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  // Only handle GET navigations/assets; never cache API/auth or POSTs.
  if (req.method !== "GET" || req.url.includes("/api/")) return;

  event.respondWith(
    fetch(req)
      .then((res) => {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => {});
        return res;
      })
      .catch(() => caches.match(req))
  );
});
